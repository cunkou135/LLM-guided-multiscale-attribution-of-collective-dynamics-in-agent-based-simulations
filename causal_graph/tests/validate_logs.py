"""Reproducible OFFLINE acceptance against actual simulations, no API calls.

python -m causal_graph.tests.validate_logs --output causal_graph/results/log_validation

Artificial responses exercise software contracts only. They are never evidence
of successful LLM generation, scientific variable quality, or causal mechanisms.
"""
import argparse
import shutil
from dataclasses import replace
from pathlib import Path
import time

import pandas as pd
from simulations.common.runner import load, run
from simulations.common.trajectory_api import Trajectory

from causal_graph.config import LLMConfig, PipelineConfig
from causal_graph.indicator_runner import execute_indicator
from causal_graph.inputs import inspect_runs, inspect_run
from causal_graph.io import digest, now, read_json, save_json
from causal_graph.pipeline import run_pipeline
from .fixtures import OfflineClient, fixture_outputs


def additional_raw_check(model, source, root, settings):
    """Hand-reviewed test functions for native raw-frame and event-table access."""
    if model == 'fish':
        code = '''import json
import pandas as pd
def compute_indicator(data, config):
    rows = data['raw_frames']
    return pd.DataFrame({'step': rows['step'], 'value': rows['frame_json'].map(lambda x: len(json.loads(x)['positions']))})
'''
        required = {'raw_frames': ['step', 'frame_json']}
        expected = pd.Series({s: len(Trajectory(source).read_frame(s)['positions']) for s in Trajectory(source).available_steps()})
    else:
        code = '''def compute_indicator(data, config):
    rows = data['events']
    return rows.groupby('step')['event_index'].count()
'''
        required = {'events': ['step', 'event_index']}
        expected = Trajectory(source).read('events').groupby('step').size()
    file = root / 'additional_code.py'
    file.write_text(code, encoding='utf-8')
    node = {'indicator_id': 'test_additional_raw', 'required': required, 'config': {},
            'code_file': file.name, 'code_sha256': digest(file), 'generation_call': 'hand_reviewed_test_fixture_only'}
    review = {'reviewer': 'offline acceptance fixture author', 'reviewed_at': now(),
              'notes': 'Handwritten test function only. Not generated by an LLM.',
              'code_sha256': {node['indicator_id']: node['code_sha256']}}
    report = execute_indicator(node, inspect_run(source), root, settings, review)
    assert report['status'] == 'success', report
    values = pd.read_parquet(root / report['series_file']).set_index('step')['value']
    pd.testing.assert_series_equal(values.astype(float), expected.astype(float), check_names=False)
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(argv)
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=False)
    settings = PipelineConfig(indicator_timeout=30)
    trusted = replace(settings, execution_mode='trusted_reviewed')
    llm = LLMConfig('offline_acceptance', 'openai_compatible', 'https://api.example.com/v1',
                    'offline-fixture-no-model-call', 'NO_KEY_USED')
    summary = {'started_at': now(), 'validation_type': 'offline_fixtures_on_real_logs',
               'real_llm_validation': 'not_requested_user_requires_interface_only', 'models': []}
    try:
        for model, field, seeds in [('fish', 'vx', [42, 43]), ('covasim', 'age', [8, 9])]:
            started = time.monotonic()
            sources = []
            for seed in seeds:
                cfg = load(f'configs/{model}.yaml')
                cfg['steps'] = 5  # Native population/mechanism unchanged; short engineering run.
                cfg['seed'] = seed
                cfg['output']['directory'] = str(root / 'simulation_runs' / model)
                sources.append(run(cfg))
            reviewed_inputs = inspect_runs(sources)
            save_json(root / f'{model}_input_audit.json', reviewed_inputs)
            experiment = root / f'{model}_offline_experiment'
            client = OfflineClient(fixture_outputs(field=field, failing=True))
            run_pipeline(sources, llm, settings, experiment, client=client, generate_only=True)
            graph = read_json(experiment / 'candidate_graph.json')
            # Approval applies exclusively to these literal, known test double functions.
            review = {'reviewer': 'offline acceptance fixture author', 'reviewed_at': now(),
                      'notes': 'Reviewed handwritten fixture aggregations only; no LLM output executed.',
                      'code_sha256': {n['indicator_id']: n['code_sha256'] for n in graph['nodes']}}
            save_json(root / f'{model}_fixture_review.json', review)
            run_pipeline(sources, llm, trusted, experiment, client=client, resume=True, approvals=review)
            reports = read_json(experiment / 'execution_report.json')
            assert sum(r['status'] == 'success' for r in reports) == 6
            assert sum(r.get('error_type') == 'unavailable_data' for r in reports) == 2
            for source in sources:
                raw = Trajectory(source).read('agent_states')
                rid = Trajectory(source).metadata()['run_id']
                for iid, method in [('test_a', 'mean'), ('test_b', 'var'), ('test_c', 'sum')]:
                    series = pd.read_parquet(experiment / 'indicator_series' / rid / f'{iid}.parquet')
                    expected = getattr(raw.groupby('step')[field], method)()
                    pd.testing.assert_series_equal(series.set_index('step')['value'], expected,
                                                   check_names=False, check_dtype=False)
            # Actual Docker boundary call; absence is observed, not monkeypatched.
            probe_root = root / f'{model}_isolation_probe'
            probe_code = probe_root / graph['nodes'][0]['code_file']
            probe_code.parent.mkdir(parents=True)
            shutil.copyfile(experiment / graph['nodes'][0]['code_file'], probe_code)
            isolation = execute_indicator(graph['nodes'][0], reviewed_inputs[0], probe_root, settings)
            extra = root / f'{model}_additional_raw_check'
            extra.mkdir()
            raw_check = additional_raw_check(model, sources[0], extra, trusted)
            row = {'model': model, 'run_ids': [r['manifest']['run_id'] for r in reviewed_inputs],
                   'actual_steps': [r['manifest']['actual_steps'] for r in reviewed_inputs],
                   'populations': [r['manifest']['parameters'].get('population', {}).get('count',
                                   r['manifest']['parameters'].get('pop_size')) for r in reviewed_inputs],
                   'successful_calculations': 6, 'expected_missing_field_failures': 2,
                   'candidate_nodes': len(graph['nodes']),
                   'executable_nodes': len(read_json(experiment / 'executable_graph.json')['nodes']),
                   'fixture_only': True, 'raw_table_check': raw_check['status'],
                   'isolation_probe': isolation, 'elapsed_seconds': time.monotonic() - started,
                   'output': str(experiment)}
            summary['models'].append(row)
            save_json(root / 'validation_summary.json', summary)
        schelling = Path('results/3b1b5e8b6f9a41d695988be12ab8c060')
        if schelling.is_dir():
            inspect_run(schelling)
            summary['schelling_compatibility'] = str(schelling.resolve())
        # Mixed models are rejected before generation.
        mixed = [root / 'simulation_runs' / m / summary['models'][i]['run_ids'][0] for i, m in enumerate(('fish', 'covasim'))]
        try:
            inspect_runs(mixed)
        except ValueError as exc:
            summary['mixed_model_rejection'] = str(exc)
        else:
            raise AssertionError('Mixed scenarios were accepted')
        summary['status'] = 'passed'
    except BaseException as exc:
        summary.update(status='failed', error=f'{type(exc).__name__}: {exc}')
        raise
    finally:
        summary['ended_at'] = now()
        save_json(root / 'validation_summary.json', summary)
    print(root / 'validation_summary.json')


if __name__ == '__main__':
    main()
